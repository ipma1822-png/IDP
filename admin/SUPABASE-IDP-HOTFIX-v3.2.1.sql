alter table public.idp_branch_applications add column if not exists region text;
alter table public.idp_branch_applications add column if not exists applicant_name text;
alter table public.idp_branch_applications add column if not exists phone text;
alter table public.idp_branch_applications add column if not exists email text;
alter table public.idp_branch_applications add column if not exists organization text;
alter table public.idp_branch_applications add column if not exists drone_qualification text;
alter table public.idp_branch_applications add column if not exists safety_experience text;
alter table public.idp_branch_applications add column if not exists expected_members integer;
alter table public.idp_branch_applications add column if not exists service_area text;
alter table public.idp_branch_applications add column if not exists plan text;
alter table public.idp_branch_applications add column if not exists notes text;
alter table public.idp_branch_applications add column if not exists status text;
