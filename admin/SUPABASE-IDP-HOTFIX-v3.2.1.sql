-- 3) 공개 신청은 테이블 직접 INSERT 대신 보안 함수(RPC)로 받습니다.
--    status/admin_note를 외부 신청자가 임의로 넣을 수 없고,
--    프로젝트별 INSERT/sequence 권한 차이에도 영향을 덜 받습니다.
create or replace function public.submit_idp_branch_application(
  p_branch_type text,
  p_branch_level text,
  p_country text,
  p_region text,
  p_applicant_name text,
  p_phone text,
  p_email text,
  p_organization text default null,
  p_drone_qualification text default null,
  p_safety_experience text default null,
  p_expected_members integer default null,
  p_service_area text default null,
  p_plan text default null,
  p_notes text default null
) returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
begin
  if nullif(trim(coalesce(p_branch_type,'')),'') is null
     or nullif(trim(coalesce(p_branch_level,'')),'') is null
     or nullif(trim(coalesce(p_country,'')),'') is null
     or nullif(trim(coalesce(p_region,'')),'') is null
     or nullif(trim(coalesce(p_applicant_name,'')),'') is null
     or nullif(trim(coalesce(p_phone,'')),'') is null
     or nullif(trim(coalesce(p_email,'')),'') is null
     or nullif(trim(coalesce(p_plan,'')),'') is null then
    raise exception '필수 신청정보가 누락되었습니다.' using errcode='22023';
  end if;

  insert into public.idp_branch_applications(
    branch_type,branch_level,country,region,applicant_name,phone,email,
    organization,drone_qualification,safety_experience,expected_members,
    service_area,plan,notes,status
  ) values (
    trim(p_branch_type),trim(p_branch_level),trim(p_country),trim(p_region),
    trim(p_applicant_name),trim(p_phone),trim(p_email),nullif(trim(coalesce(p_organization,'')),''),
    nullif(trim(coalesce(p_drone_qualification,'')),''),nullif(trim(coalesce(p_safety_experience,'')),''),
    p_expected_members,nullif(trim(coalesce(p_service_area,'')),''),trim(p_plan),
    nullif(trim(coalesce(p_notes,'')),''),'pending'
  ) returning id into v_id;

  return v_id;
end;
$$;

revoke all on function public.submit_idp_branch_application(text,text,text,text,text,text,text,text,text,text,integer,text,text,text) from public;
grant execute on function public.submit_idp_branch_application(text,text,text,text,text,text,text,text,text,text,integer,text,text,text) to anon, authenticated;

-- 기존 공개 직접 INSERT 정책은 더 이상 필요하지 않습니다.
drop policy if exists "IDP public insert branch applications" on public.idp_branch_applications;
revoke insert on public.idp_branch_applications from anon;

-- 4) 17개 시·도 조직 공개조회/관리자 수정 권한도 확실히 보강합니다.
